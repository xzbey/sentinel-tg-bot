CLASS_TEXT = """🎯 <b>Классификация</b>
 
Каждому пикселю присваивается один из классов:
• 🟦 Вода
• 🟥 Застройка / Открытый грунт
• 🟩 Растительность
• 🟨 Прочее
• ⬛ Нет данных
 
<u>По чему классифицируем</u>
Используются каналы B03, B04, B08, B11 (отражение от 0 до 1) и индексы NDVI, MNDWI, NDBI.
 
<u>Правила (значения по умолчанию)</u>
• <b>Вода:</b> MNDWI больше -0.1, B08 меньше 0.1 и B11 меньше 0.05. Вода почти не отражает ближний и коротковолновый ИК.
• <b>Застройка / Открытый грунт:</b> разность NDBI - NDVI больше -0.4 и B04 больше 0.04 (отсекает очень темные пиксели).
• <b>Растительность:</b> NDVI больше 0.25 и B08 больше 0.1.
• <b>Прочее:</b> все остальное.
Если пиксель подходит под несколько классов, приоритет такой: вода > застройка > растительность. Пиксели без данных (dataMask = 0) получают код 0.
 
<u>Очистка шума</u>
Маска застройки сначала склеивается (морфологическое замыкание, окно 5x5 пикселей) и очищается от пятен меньше 6 пикселей. Затем итоговая карта очищается от пятен меньше 4 пикселей: мелкие группы заменяются классом соседей.
 
<u>Какие пороги меняют кнопки</u>
• Вода - порог по B08 (по умолчанию 0.1, шаг 0.02, от 0.04 до 0.16). Больше воды - порог выше.
• Застройка - порог разности NDBI - NDVI (по умолчанию -0.4, шаг 0.1, от -0.7 до -0.1). Больше застройки - порог ниже.
• Растительность - порог NDVI (по умолчанию 0.25, шаг 0.05, от 0.1 до 0.4). Больше растительности - порог ниже.
 
<u>Подстройка</u>
Кнопки "Больше / Меньше" для воды, застройки и растительности сдвигают пороги на один шаг. Каждое нажатие пересчитывает карту из уже загруженных данных и присылает новое сообщение с картой и GeoTIFF. В подписи указано накопленное число шагов. У каждого параметра есть предел, при его достижении бот сообщит об этом.
Повторное нажатие кнопки "Классификация" в меню сбрасывает все поправки.
 
<u>Результат</u>
Карта с легендой и GeoTIFF с одним каналом (uint8): 1 - вода, 2 - застройка / открытый грунт, 3 - растительность, 4 - прочее, 0 - нет данных.
 
<u>Ограничения</u>
Метод простой, на порогах, и не универсален для всех мест и дат. Застройку и голую почву, пески, вспаханные поля он не различает, мелкие водоемы (меньше 2-3 пикселей) теряются, тени могут давать ложную воду. Для подстройки используйте кнопки."""

