INDICES_TEXT = """📊 <b>Индексы</b>
 
Индекс - формула над двумя каналами: <code>(A - B) / (A + B)</code>. Значения от -1 до 1. Раскраска turbo_r с фиксированной шкалой от -1 до 1, поэтому индексы разных дат можно сравнивать. Черный цвет - нет данных.
 
<b>NDVI</b> = (B08 - B04) / (B08 + B04)
Растительность. Выше примерно 0.3 - растительность, около 0 - голая почва и застройка, ниже 0 - вода, снег, облака.
 
<b>MNDWI</b> = (B03 - B11) / (B03 + B11)
Вода 1 вариант. Также имеет название <b>NDSI</b>. Больше 0 - вода. Лучше NDWI отсекает застройку, но B11 имеет разрешение 20 м, поэтому мелкие водоемы получаются блочными.
 
<b>NDWI</b> = (B03 - B08) / (B03 + B08)
Вода 2 вариант. В городе может принимать крыши и асфальт за воду.
 
<b>NBR</b> = (B08 - B12) / (B08 + B12)
Гари. Низкие значения - выжженные территории, высокие - здоровая растительность. На одном снимке гарь различается слабо, надежнее сравнивать снимки до и после пожара.
 
<b>NDBI</b> = (B11 - B08) / (B11 + B08)
Застройка. Больше 0 - застройка и открытый грунт. Голую почву от застройки не отличает.
 
<u>Результат</u>
Картинка с цветовой шкалой и GeoTIFF с одним каналом (float32). В пикселях без данных значение NaN. В QGIS можно выбрать свою раскраску.
 
Каналы B11 и B12 имеют родное разрешение 20 м и растянуты до сетки снимка, поэтому у MNDWI, NDBI и NBR заметна блочность. Недостающие каналы бот докачивает один раз при первом нажатии."""

